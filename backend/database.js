const fs = require("fs");
const path = require("path");
const { Pool } = require("pg");

const dataDir = path.join(__dirname, "data");
const hasDatabaseUrl = Boolean(process.env.DATABASE_URL);
const hasDatabaseParts = ["DB_HOST", "DB_NAME", "DB_USER", "DB_PASSWORD"]
  .every((key) => process.env[key]);
const isConfigured = hasDatabaseUrl || hasDatabaseParts;

const pool = isConfigured
  ? new Pool({
      ...(hasDatabaseUrl
        ? { connectionString: process.env.DATABASE_URL }
        : {
            host: process.env.DB_HOST,
            port: Number(process.env.DB_PORT || 5432),
            database: process.env.DB_NAME,
            user: process.env.DB_USER,
            password: process.env.DB_PASSWORD,
          }),
      ...(process.env.DB_SSL === "true"
        ? {
            ssl: {
              rejectUnauthorized: process.env.DB_SSL_REJECT_UNAUTHORIZED !== "false",
            },
          }
        : {}),
    })
  : null;

function readSeed(fileName) {
  try {
    return JSON.parse(fs.readFileSync(path.join(dataDir, fileName), "utf8"));
  } catch {
    return [];
  }
}

async function seedIfEmpty(client, table, rows, insertRow) {
  const { rows: imports } = await client.query(
    "SELECT table_name FROM data_seed_imports WHERE table_name = $1",
    [table]
  );
  if (imports.length) return;

  const { rows: existing } = await client.query(`SELECT COUNT(*)::int AS count FROM ${table}`);
  if (existing[0].count === 0) {
    for (const row of rows) {
      await insertRow(client, row);
    }
  }
  await client.query(
    "INSERT INTO data_seed_imports (table_name) VALUES ($1) ON CONFLICT DO NOTHING",
    [table]
  );
}

async function initializeDatabase() {
  if (!pool) {
    console.warn("PostgreSQL no está configurado; se usará el almacenamiento JSON local.");
    return;
  }

  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    await client.query(`
      CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        email TEXT NOT NULL UNIQUE,
        role TEXT NOT NULL DEFAULT 'Visualizador',
        team TEXT NOT NULL DEFAULT 'Sin equipo',
        area TEXT NOT NULL DEFAULT 'Sin área',
        phone TEXT NOT NULL DEFAULT '',
        status TEXT NOT NULL DEFAULT 'Activo',
        avatar_path TEXT,
        last_login_at TIMESTAMPTZ
      );
      CREATE TABLE IF NOT EXISTS data_seed_imports (
        table_name TEXT PRIMARY KEY,
        imported_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE TABLE IF NOT EXISTS folders (
        id TEXT PRIMARY KEY,
        name TEXT NOT NULL UNIQUE,
        owner_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
        is_shared BOOLEAN NOT NULL DEFAULT TRUE,
        access_roles TEXT[] NOT NULL DEFAULT ARRAY['Administrador', 'Editor', 'Revisor', 'Visualizador'],
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE TABLE IF NOT EXISTS documents (
        id TEXT PRIMARY KEY,
        name TEXT NOT NULL,
        stored_name TEXT NOT NULL,
        mime_type TEXT NOT NULL,
        size BIGINT NOT NULL,
        folder_id TEXT,
        document_type TEXT NOT NULL DEFAULT 'Sin clasificar',
        is_shared BOOLEAN NOT NULL DEFAULT TRUE,
        owner_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      ALTER TABLE users ADD COLUMN IF NOT EXISTS last_login_at TIMESTAMPTZ;
      ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_path TEXT;
      ALTER TABLE folders ADD COLUMN IF NOT EXISTS owner_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL;
      ALTER TABLE folders ADD COLUMN IF NOT EXISTS is_shared BOOLEAN NOT NULL DEFAULT TRUE;
      ALTER TABLE folders ADD COLUMN IF NOT EXISTS access_roles TEXT[] NOT NULL DEFAULT ARRAY['Administrador', 'Editor', 'Revisor', 'Visualizador'];
      ALTER TABLE folders DROP CONSTRAINT IF EXISTS folders_name_key;
      DROP INDEX IF EXISTS folders_shared_name_idx;
      CREATE UNIQUE INDEX IF NOT EXISTS folders_shared_owner_name_idx
        ON folders (lower(name), owner_user_id) WHERE is_shared = TRUE;
      CREATE UNIQUE INDEX IF NOT EXISTS folders_private_owner_name_idx ON folders (lower(name), owner_user_id) WHERE is_shared = FALSE;
      CREATE TABLE IF NOT EXISTS hidden_folders (
        folder_id TEXT NOT NULL REFERENCES folders(id) ON DELETE CASCADE,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        PRIMARY KEY (folder_id, user_id)
      );
      CREATE TABLE IF NOT EXISTS hidden_documents (
        document_id TEXT NOT NULL,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        PRIMARY KEY (document_id, user_id)
      );
      CREATE TABLE IF NOT EXISTS trash_items (
        id TEXT PRIMARY KEY,
        item_type TEXT NOT NULL CHECK (item_type IN ('folder', 'document')),
        item_id TEXT NOT NULL,
        batch_id TEXT NOT NULL,
        name TEXT NOT NULL,
        folder_id TEXT,
        audience TEXT NOT NULL CHECK (audience IN ('personal', 'global')),
        owner_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
        deleted_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
        deleted_by_name TEXT NOT NULL,
        deleted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        payload JSONB NOT NULL
      );
      CREATE INDEX IF NOT EXISTS trash_items_personal_idx ON trash_items (deleted_by_user_id, deleted_at DESC);
      CREATE INDEX IF NOT EXISTS trash_items_batch_idx ON trash_items (batch_id);
      ALTER TABLE documents ADD COLUMN IF NOT EXISTS document_type TEXT NOT NULL DEFAULT 'Sin clasificar';
      ALTER TABLE documents ADD COLUMN IF NOT EXISTS is_shared BOOLEAN NOT NULL DEFAULT TRUE;
      ALTER TABLE documents ADD COLUMN IF NOT EXISTS owner_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL;
      CREATE INDEX IF NOT EXISTS documents_folder_owner_idx ON documents (folder_id, owner_user_id);
      CREATE TABLE IF NOT EXISTS user_sessions (
        session_id TEXT PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        username TEXT NOT NULL,
        logged_in_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        expires_at TIMESTAMPTZ NOT NULL,
        logged_out_at TIMESTAMPTZ
      );
      CREATE TABLE IF NOT EXISTS app_settings (
        key TEXT PRIMARY KEY,
        value JSONB NOT NULL
      );
      CREATE INDEX IF NOT EXISTS user_sessions_active_idx
        ON user_sessions (user_id, expires_at) WHERE logged_out_at IS NULL;
    `);

    await seedIfEmpty(client, "users", readSeed("users.json"), (db, user) =>
      db.query(
        `INSERT INTO users (id, name, email, role, team, area, phone, status)
         VALUES ($1, $2, $3, $4, $5, $6, $7, $8) ON CONFLICT DO NOTHING`,
        [user.id, user.name, user.email, user.role, user.team, user.area, user.phone, user.status]
      )
    );
    await client.query(
      `SELECT setval(pg_get_serial_sequence('users', 'id'), COALESCE(MAX(id), 1), COUNT(*) > 0) FROM users`
    );

    await seedIfEmpty(client, "folders", readSeed("folders.json"), (db, folder) =>
      db.query(
        `INSERT INTO folders (id, name, created_at) VALUES ($1, $2, $3) ON CONFLICT DO NOTHING`,
        [folder.id, folder.name, folder.createdAt || new Date().toISOString()]
      )
    );
    await seedIfEmpty(client, "documents", readSeed("documents.json"), (db, document) =>
      db.query(
        `INSERT INTO documents (id, name, stored_name, mime_type, size, folder_id, document_type, created_at)
         VALUES ($1, $2, $3, $4, $5, $6, $7, $8) ON CONFLICT DO NOTHING`,
        [document.id, document.name, document.storedName, document.mimeType, document.size,
          document.folderId || null, document.documentType || "Sin clasificar",
          document.createdAt || new Date().toISOString()]
      )
    );

    await client.query("UPDATE user_sessions SET logged_out_at = NOW() WHERE logged_out_at IS NULL");

    await client.query("COMMIT");
    console.log("Conexión PostgreSQL lista; tablas verificadas y datos JSON importados si estaban vacías.");
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
}

module.exports = { isConfigured, initializeDatabase, pool };